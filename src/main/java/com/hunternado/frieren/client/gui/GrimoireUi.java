package com.hunternado.frieren.client.gui;

import com.hunternado.frieren.FrierenIds;
import com.hunternado.frieren.magic.SpellRarity;
import com.hunternado.frieren.magic.SpellSchool;
import com.hunternado.frieren.spell.OriginalSpells;
import com.hunternado.frieren.spell.SpellDefinition;
import net.minecraft.client.gui.Font;
import net.minecraft.client.gui.GuiGraphicsExtractor;
import net.minecraft.client.renderer.RenderPipelines;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.Identifier;

/**
 * Shared drawing for the grimoire-styled screens: the leather book, parchment sheets, ink buttons, spell icons and
 * the ink palette. All art lives in the GUI atlas (textures/gui/sprites/, generated by tools/gen_gui.py); panels are
 * nine-slice sprites, so any size works.
 */
public final class GrimoireUi {
    public static final int INK = 0xFF3A2A1C;
    public static final int INK_SOFT = 0xFF6B5440;
    public static final int INK_FAINT = 0xFF9A8464;
    public static final int INK_GOLD = 0xFF9A6A18;
    public static final int INK_RED = 0xFF8E2A20;
    public static final int INK_GREEN = 0xFF3E6A28;
    public static final int INK_BLUE = 0xFF2A4E86;
    public static final int RULE = 0x66745A3A;

    private static final Identifier COVER = FrierenIds.id("book/cover");
    private static final Identifier PAGE_LEFT = FrierenIds.id("book/page_left");
    private static final Identifier PAGE_RIGHT = FrierenIds.id("book/page_right");
    private static final Identifier RIBBON = FrierenIds.id("book/ribbon");
    private static final Identifier CIRCLE = FrierenIds.id("book/circle");
    private static final Identifier ROW_HOVER = FrierenIds.id("book/row_hover");
    private static final Identifier ROW_SELECTED = FrierenIds.id("book/row_selected");
    private static final Identifier BUTTON = FrierenIds.id("book/button_normal");
    private static final Identifier BUTTON_HOVER = FrierenIds.id("book/button_hover");
    private static final Identifier BUTTON_DISABLED = FrierenIds.id("book/button_disabled");
    public static final Identifier SLOT = FrierenIds.id("hud/slot");
    public static final Identifier SLOT_SELECTED = FrierenIds.id("hud/slot_selected");

    private GrimoireUi() {}

    public static void sprite(GuiGraphicsExtractor graphics, Identifier sprite, int x, int y, int w, int h) {
        graphics.blitSprite(RenderPipelines.GUI_TEXTURED, sprite, x, y, w, h);
    }

    public static void sprite(GuiGraphicsExtractor graphics, Identifier sprite, int x, int y, int w, int h, int argb) {
        graphics.blitSprite(RenderPipelines.GUI_TEXTURED, sprite, x, y, w, h, argb);
    }

    /** The open book: leather cover with both pages. Returns nothing; pages sit 6px inside the cover. */
    public static void book(GuiGraphicsExtractor graphics, int x, int y, int w, int h) {
        sprite(graphics, COVER, x, y, w, h);
        int half = w / 2;
        sprite(graphics, PAGE_LEFT, x + 6, y + 5, half - 6, h - 10);
        sprite(graphics, PAGE_RIGHT, x + half, y + 5, w - half - 6, h - 10);
        // the spine: a dark crease where the pages meet
        graphics.fill(x + half - 1, y + 5, x + half + 1, y + h - 5, 0x55301E10);
    }

    /** A single parchment sheet on a leather backing, for smaller screens (examiner, trader). */
    public static void sheet(GuiGraphicsExtractor graphics, int x, int y, int w, int h) {
        sprite(graphics, COVER, x, y, w, h);
        sprite(graphics, PAGE_RIGHT, x + 5, y + 5, w - 10, h - 10);
    }

    /** A bookmark ribbon hanging from {@code top}; {@code length} pixels of it are drawn. */
    public static void ribbon(GuiGraphicsExtractor graphics, int x, int top, int length, int argb) {
        sprite(graphics, RIBBON, x, top, 10, length, argb);
    }

    public static void circle(GuiGraphicsExtractor graphics, int cx, int cy, int size) {
        sprite(graphics, CIRCLE, cx - size / 2, cy - size / 2, size, size);
    }

    public static void row(GuiGraphicsExtractor graphics, int x, int y, int w, int h, boolean selected, boolean hovered) {
        if (selected) {
            sprite(graphics, ROW_SELECTED, x, y, w, h);
        } else if (hovered) {
            sprite(graphics, ROW_HOVER, x, y, w, h);
        }
    }

    /** An ink-stamped button with a centred label; returns whether the mouse is over it. */
    public static boolean button(GuiGraphicsExtractor graphics, Font font, Component label, int x, int y, int w, int h,
                                 int mouseX, int mouseY, boolean active) {
        boolean hovered = active && inside(mouseX, mouseY, x, y, w, h);
        sprite(graphics, !active ? BUTTON_DISABLED : hovered ? BUTTON_HOVER : BUTTON, x, y, w, h);
        graphics.text(font, label, x + (w - font.width(label)) / 2, y + (h - 8) / 2, active ? INK : INK_FAINT, false);
        return hovered;
    }

    /** A thin ink rule with a small diamond in the middle. */
    public static void divider(GuiGraphicsExtractor graphics, int x, int y, int w) {
        graphics.fill(x, y, x + w, y + 1, RULE);
        int cx = x + w / 2;
        graphics.fill(cx - 1, y - 1, cx + 2, y + 2, 0xAA745A3A);
        graphics.fill(cx, y - 2, cx + 1, y + 3, 0xAA745A3A);
    }

    public static void centered(GuiGraphicsExtractor graphics, Font font, Component text, int cx, int y, int color) {
        graphics.text(font, text, cx - font.width(text) / 2, y, color, false);
    }

    /** The spell's own icon, its form's picture for Original magic, or the generic rune tinted with the spell's colour. */
    public static void spellIcon(GuiGraphicsExtractor graphics, Identifier spell, SpellDefinition definition, int x, int y, int size) {
        if (definition != null && definition.school() == SpellSchool.ORIGINAL) {
            int form = Math.max(0, Math.min(OriginalSpells.FORMS.length - 1, (int) definition.param("form", 0.0D)));
            sprite(graphics, FrierenIds.id("spell/original_" + OriginalSpells.FORMS[form]), x, y, size, size, 0xFF000000 | definition.color());
            return;
        }
        if (SpellIcons.hasIcon(spell)) {
            sprite(graphics, SpellIcons.sprite(spell), x, y, size, size);
        } else {
            sprite(graphics, SpellIcons.GENERIC, x, y, size, size, 0xFF000000 | (definition != null ? definition.color() : 0xFFFFFF));
        }
    }

    public static Identifier gem(SpellRarity rarity) {
        return FrierenIds.id("gem/" + rarity.serializedName());
    }

    public static Identifier stat(String kind) {
        return FrierenIds.id("stat/" + kind);
    }

    /** Ribbon colour per school (the "all" tab is gold). */
    public static int schoolColor(SpellSchool school) {
        if (school == null) {
            return 0xFFE2B54A;
        }
        return switch (school) {
            case OFFENSIVE -> 0xFFC8443A;
            case DEFENSIVE -> 0xFF4A7ED0;
            case UTILITY -> 0xFF6AAE48;
            case SPECIAL -> 0xFF8A5AC8;
            case ORIGINAL -> 0xFFE8A030;
        };
    }

    /** Ink colour for a rarity name on parchment (the chat colours are unreadable on cream). */
    public static int rarityInk(SpellRarity rarity) {
        return switch (rarity) {
            case COMMON -> INK_SOFT;
            case UNCOMMON -> INK_GREEN;
            case RARE -> INK_BLUE;
            case ANCIENT -> INK_GOLD;
            case LEGENDARY -> 0xFF8A2E8E;
            case DEMON -> INK_RED;
            case FORBIDDEN -> 0xFF4A1E6E;
            case MYTHIC -> 0xFFB8641A;
        };
    }

    /** Cuts text to fit {@code width}, ending in an ellipsis when anything was cut. */
    public static String fit(Font font, String text, int width) {
        if (font.width(text) <= width) {
            return text;
        }
        return font.plainSubstrByWidth(text, Math.max(0, width - font.width("…"))).stripTrailing() + "…";
    }

    /** The text without its chat colours, so it can be inked onto parchment. */
    public static Component plain(Component text) {
        return Component.literal(text.getString());
    }

    public static boolean inside(double mouseX, double mouseY, int x, int y, int w, int h) {
        return mouseX >= x && mouseX < x + w && mouseY >= y && mouseY < y + h;
    }
}
